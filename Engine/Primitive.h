enum class PrimitiveType {
	TETRAHEDRON = 0,
	ICOSAHEDRON = 1,
	CUBE = 2,
	PYRAMID = 3,
	CYLINDER = 4,
	SPHERE = 5

};

struct PrimitiveMesh {
	GLuint VAO = 0;
	GLuint VBO = 0;
	GLuint EBO = 0;
	GLsizei n_index = 0;
};

struct PrimitiveEntity {
	PrimitiveType type = PrimitiveType::ICOSAHEDRON;
	glm::vec3 position{ 0.0f };
	glm::vec3 scale{ 1.0f };
	float rotation = 0.0f;
};

class Primitive {
public:
	Primitive() {}
	Primitive(PrimitiveMesh mesh, PrimitiveEntity entity, Texture texture) {
		this->mesh = mesh;
		this->entity = entity;
		this->texture = texture;
	}
	~Primitive() {}

	PrimitiveMesh mesh;
	PrimitiveEntity entity;
	Texture texture;
};

